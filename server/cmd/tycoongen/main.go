// Command tycoongen exports server-authoritative Tycoon constants and parity fixtures.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"ola-chat-server/internal/game/games/tycoon"
)

func main() {
	constantsPath := flag.String("constants", "", "output path for generated TypeScript constants, board and cards")
	parityPath := flag.String("parity", "", "output path for the JSON parity fixture")
	stressPath := flag.String("stress", "", "output path for a large fixture with the state after every turn")
	games := flag.Int("games", 200, "number of games in the stress fixture")
	flag.Parse()
	if *constantsPath == "" && *parityPath == "" && *stressPath == "" {
		fmt.Fprintln(os.Stderr, "-constants, -parity or -stress is required")
		os.Exit(2)
	}
	if *constantsPath != "" {
		data, err := renderConstants()
		if err == nil {
			err = writeFile(*constantsPath, data)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if *parityPath != "" {
		if err := writeFixture(*parityPath, tycoon.ExportParityFixture()); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if *stressPath != "" {
		if err := writeFixture(*stressPath, tycoon.ExportStressFixture(*games)); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func renderConstants() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by server/cmd/tycoongen; DO NOT EDIT.\n\n")
	ints := []struct {
		name  string
		value int
	}{
		{"TURN_SECONDS", tycoon.TurnSeconds},
		{"MIN_PLAYERS", tycoon.MinPlayers},
		{"MAX_PLAYERS", tycoon.MaxPlayers},
		{"BOARD_SIZE", tycoon.BoardSize},
		{"SIDE_TILES", tycoon.SideTiles},
		{"START_CASH", tycoon.StartCash},
		{"GO_SALARY", tycoon.GoSalary},
		{"JAIL_FINE", tycoon.JailFine},
		{"JAIL_TILE", tycoon.JailTile},
		{"MAX_HOUSES", tycoon.MaxHouses},
		{"MAX_ROUNDS", tycoon.MaxRounds},
		{"TIME_LIMIT_MS", int(tycoon.TimeLimit.Milliseconds())},
		{"TAKEOVER_MULTIPLIER", tycoon.TakeoverMultiplier},
		{"WIN_GROUPS", tycoon.WinGroups},
		{"MAX_DOUBLES", tycoon.MaxDoubles},
		{"JAIL_MAX_TURNS", tycoon.JailMaxTurns},
		{"BIRTHDAY_GIFT", tycoon.BirthdayGift},
		{"FESTIVAL_MULTIPLIER", tycoon.FestivalMultiplier},
	}
	fmt.Fprintf(&out, "export const GAME_ID = %q;\n", tycoon.GameID)
	for _, item := range ints {
		fmt.Fprintf(&out, "export const %s = %d;\n", item.name, item.value)
	}
	fmt.Fprintf(&out, "export const TAX_RATE = %g;\n", tycoon.TaxRate)
	fmt.Fprintf(&out, "export const ERROR_PREFIX = %q;\n", tycoon.ErrorPrefix)
	rent := make([]string, len(tycoon.StationRent))
	for i, value := range tycoon.StationRent {
		rent[i] = fmt.Sprint(value)
	}
	fmt.Fprintf(&out, "export const STATION_RENT = [%s] as const;\n", strings.Join(rent, ", "))

	writeList := func(name, typeName string, values []string) {
		fmt.Fprintf(&out, "\nexport const %s = [\n", name)
		for _, value := range values {
			fmt.Fprintf(&out, "  %q,\n", value)
		}
		fmt.Fprintf(&out, "] as const;\nexport type %s = (typeof %s)[number];\n", typeName, name)
	}
	writeList("PHASES", "Phase", tycoon.Phases)
	writeList("MOVE_TYPES", "MoveType", tycoon.MoveTypes)
	writeList("STEP_KINDS", "StepKind", tycoon.StepKinds)
	writeList("TILE_KINDS", "TileKind", []string{tycoon.KindGo, tycoon.KindStreet, tycoon.KindStation, tycoon.KindChance, tycoon.KindChest, tycoon.KindTax, tycoon.KindJail, tycoon.KindFestival, tycoon.KindTravel})
	writeList("GROUPS", "Group", []string{tycoon.GroupBrown, tycoon.GroupSky, tycoon.GroupPink, tycoon.GroupOrange, tycoon.GroupRed, tycoon.GroupYellow, tycoon.GroupGreen, tycoon.GroupBlue, tycoon.GroupStation})
	writeList("PAY_REASONS", "PayReason", []string{tycoon.PayRent, tycoon.PayTax, tycoon.PayCard, tycoon.PayFine, tycoon.PayRepair, tycoon.PayBirthday, tycoon.PayBuy, tycoon.PayBuild, tycoon.PaySell, tycoon.PaySalary, tycoon.PayTakeover})
	writeList("END_REASONS", "EndReason", tycoon.EndReasons)
	writeList("ERROR_CODES", "ErrorCode", []string{
		tycoon.ErrFinished, tycoon.ErrNotActive, tycoon.ErrNotYourTurn, tycoon.ErrWrongPhase, tycoon.ErrInvalidTile, tycoon.ErrInvalidMove,
		tycoon.ErrUnknownMove, tycoon.ErrNoCash, tycoon.ErrNoJailCard, tycoon.ErrNotStreet, tycoon.ErrNotOwner, tycoon.ErrNotGroupOwner,
		tycoon.ErrMaxHouses, tycoon.ErrBuildUneven, tycoon.ErrNoHouses, tycoon.ErrSellUneven, tycoon.ErrNotTakeover, tycoon.ErrTakeoverHotel,
	})

	board, err := json.MarshalIndent(tycoon.Board, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode board: %w", err)
	}
	cards, err := json.MarshalIndent(tycoon.Cards, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode cards: %w", err)
	}
	fmt.Fprintf(&out, "\nexport const BOARD_DATA = %s;\n", board)
	fmt.Fprintf(&out, "\nexport const CARD_DATA = %s;\n", cards)
	return out.Bytes(), nil
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

func writeFixture(path string, fixture tycoon.ParityFixture) error {
	data, err := tycoon.EncodeParityFixture(fixture)
	if err != nil {
		return fmt.Errorf("encode %s: %w", path, err)
	}
	return writeFile(path, data)
}
